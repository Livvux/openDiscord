import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import { Pool } from "pg";
import { CAPTCHA_HEADER, expectNoA11yViolations, newUserPage } from "./helpers";

test("global administration works without 2FA and applies reports and suspensions", async ({ browser, baseURL }, testInfo) => {
  test.setTimeout(120_000);
  const page = await newUserPage(browser);
  const db = new Pool({ connectionString: process.env.DATABASE_URL });
  const suffix = `${testInfo.project.name}-${randomUUID()}`;
  const password = "correct horse battery";
  const email = `instance-admin-${suffix}@example.test`;
  const adminSignup = await page.request.post("/api/auth/sign-up/email", { headers: { Origin: baseURL!, ...CAPTCHA_HEADER }, data: { email, password, name: "QA Instance Admin" } });
  expect(adminSignup.ok()).toBe(true);
  const adminId: string = (await adminSignup.json()).user.id;
  const chatter = await newUserPage(browser);
  const memberContext = chatter.context();
  page.setDefaultTimeout(15_000);
  chatter.setDefaultTimeout(15_000);
  const runtimeErrors: string[] = [];
  page.on("pageerror", (error) => runtimeErrors.push(error.message));
  chatter.on("pageerror", (error) => runtimeErrors.push(error.message));
  let chatterId: string | undefined;
  let communityId: string | undefined;
  try {
    // Test-only role fixture. Runtime grants are exposed exclusively through authenticated admin actions.
    await db.query("insert into instance_admin (user_id) values ($1)", [adminId]);
    await page.goto("/app/admin");
    await expect(page.getByRole("heading", { name: "Instance control" })).toBeVisible();
    await expect(page.getByLabel("Authenticator code")).toHaveCount(0);
    await expectNoA11yViolations(page);

    const chatterEmail = `chatter-${suffix}@example.test`;
    const signup = await chatter.request.post("/api/auth/sign-up/email", { headers: { Origin: baseURL!, ...CAPTCHA_HEADER }, data: { email: chatterEmail, password, name: "QA Chatter" } });
    expect(signup.ok()).toBe(true);
    chatterId = (await signup.json()).user.id;
    await chatter.goto("/app");
    await chatter.getByRole("button", { name: "Create a community", exact: true }).last().click();
    await chatter.getByLabel("Name", { exact: true }).fill(`QA moderation ${suffix}`);
    await chatter.getByRole("button", { name: "Create", exact: true }).click();
    await expect(chatter).toHaveURL(/\/app\/c\/[\w-]+\/[\w-]+/);
    const channelUrl = chatter.url();
    communityId = new URL(channelUrl).pathname.split("/")[3];
    const channelId = new URL(channelUrl).pathname.split("/")[4];
    await chatter.locator("textarea").fill("QA reported private message");
    await chatter.locator("textarea").press("Enter");
    await expect(chatter.getByText("QA reported private message", { exact: true })).toBeVisible();
    await chatter.getByRole("button", { name: "Report message", exact: true }).click();
    await chatter.getByLabel("Why are you reporting this message?").fill("QA message abuse report");
    await chatter.getByRole("button", { name: "Submit report" }).click();
    await expect(chatter.getByRole("status")).toContainText("Report submitted");
    await chatter.keyboard.press("Escape");
    if (testInfo.project.use.isMobile) await chatter.getByRole("button", { name: "Open navigation", exact: true }).click();
    await chatter.getByRole("button", { name: "Report community", exact: true }).click();
    await chatter.getByLabel("Why are you reporting this community?").fill("QA community abuse report");
    await chatter.getByRole("button", { name: "Submit report" }).click();
    await expect(chatter.getByRole("status")).toContainText("Report submitted");
    await chatter.keyboard.press("Escape");
    await chatter.goto("/app/admin");
    await expect(chatter.getByRole("heading", { name: "This page could not be found" })).toBeVisible();
    await chatter.goto(channelUrl);

    await page.goto("/app/admin?tab=reports");
    await expect(page.getByText("QA message abuse report", { exact: true })).toBeVisible();
    await expect(page.getByText("QA reported private message", { exact: true })).toHaveCount(0);
    const report = page.locator("#reports li").filter({ hasText: "QA message abuse report" });
    await report.getByRole("button", { name: "Review reported message", exact: true }).click();
    await page.getByLabel("Reason", { exact: true }).fill("QA explicit private-content review");
    await page.getByRole("button", { name: "Confirm review reported message", exact: true }).click();
    await expect(report.getByText("QA reported private message", { exact: true })).toBeVisible();
    await report.getByRole("button", { name: "Remove reported message", exact: true }).click();
    await page.getByLabel("Reason", { exact: true }).fill("QA confirmed abusive content");
    await page.getByRole("button", { name: "Confirm remove reported message", exact: true }).click();
    await expect(page.getByText("QA message abuse report", { exact: true })).toHaveCount(0);
    await expect(chatter.getByText("QA reported private message", { exact: true })).toHaveCount(0);
    const removed = await db.query("select count(*)::int as total from message where content=$1 and author_id=$2", ["QA reported private message", chatterId]);
    expect(removed.rows[0].total).toBe(0);
    const log = await db.query("select count(*)::int as total from instance_audit_log where actor_id=$1 and action='report.content.view'", [adminId]);
    expect(log.rows[0].total).toBe(1);

    await page.goto("/app/admin?tab=users");
    await page.getByLabel("Search users by name or email").fill(chatterEmail);
    await page.getByRole("button", { name: "Search", exact: true }).click();
    const userRow = page.locator("#users li").filter({ hasText: chatterEmail });
    await userRow.getByRole("button", { name: "Suspend user", exact: true }).click();
    await page.getByLabel("Reason", { exact: true }).fill("QA account suspension");
    await page.getByRole("button", { name: "Confirm suspend user", exact: true }).click();
    await expect(page.locator("#users")).toContainText("Suspended: QA account suspension");
    await expect(chatter).toHaveURL(/\/sign-in/);
    expect((await chatter.request.get(`/api/channels/${channelId}/messages`)).status()).toBe(401);
    expect((await chatter.request.head(`/api/communities/${communityId}/events`)).status()).toBe(401);
    await userRow.getByRole("button", { name: "Unsuspend user", exact: true }).click();
    await page.getByLabel("Reason", { exact: true }).fill("QA suspension appeal");
    await page.getByRole("button", { name: "Confirm unsuspend user", exact: true }).click();
    await expect(userRow).toContainText("Active");
    await chatter.getByLabel("Email", { exact: true }).fill(chatterEmail);
    await chatter.getByLabel("Password", { exact: true }).fill(password);
    await chatter.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(chatter).toHaveURL(/\/app\/c\//);

    await page.goto("/app/admin?tab=communities");
    await page.getByLabel("Search communities by name").fill(`QA moderation ${suffix}`);
    await page.getByRole("button", { name: "Search", exact: true }).click();
    const communityRow = page.locator("#communities li").filter({ hasText: suffix });
    await communityRow.getByRole("button", { name: "Suspend community", exact: true }).click();
    await page.getByLabel("Reason", { exact: true }).fill("QA community suspension");
    await page.getByRole("button", { name: "Confirm suspend community", exact: true }).click();
    await expect(communityRow).toContainText("Suspended: QA community suspension");
    await expect(chatter.getByRole("heading", { name: "Welcome, QA Chatter" })).toBeVisible();
    expect((await chatter.request.get(`/api/channels/${channelId}/messages`)).status()).toBe(404);
    expect((await chatter.request.head(`/api/communities/${communityId}/events`)).status()).toBe(404);
    await expectNoA11yViolations(page);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(runtimeErrors).toEqual([]);
    await page.screenshot({ path: testInfo.outputPath("instance-administration.png"), fullPage: true });
  } finally {
    await memberContext.close().catch(() => {});
    await page.context().close().catch(() => {});
    if (communityId) await db.query("delete from community where id=$1", [communityId]);
    await db.query("delete from abuse_report where reporter_id=$1", [chatterId ?? "missing"]);
    await db.query("delete from instance_audit_log where actor_id=$1", [adminId]);
    await db.query("delete from instance_admin where user_id=$1", [adminId]);
    await db.query('delete from "user" where id=any($1::text[])', [[adminId, ...(chatterId ? [chatterId] : [])]]);
    await db.end();
  }
});
