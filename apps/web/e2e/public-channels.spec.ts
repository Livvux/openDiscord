import { expect, test } from "@playwright/test";
import { createCommunity, createInviteLink, expectNoA11yViolations, joinAsNewUser, newUserPage, signUp } from "./helpers";

test("explicit public creation, member consent, anonymous discovery, report and terminal unpublish", async ({ browser, isMobile }, testInfo) => {
  const owner = await newUserPage(browser);
  const errors: string[] = [];
  owner.on("pageerror", (error) => errors.push(error.message));
  await signUp(owner, "Public Owner");
  await createCommunity(owner, "PRIVATE WORKSHOP NAME");
  const privateId = owner.url().split("/").pop()!;
  if (isMobile) await owner.getByRole("button", { name: "Open navigation" }).click();
  const invite = await createInviteLink(owner);
  if (isMobile) await owner.keyboard.press("Escape");
  const member = await joinAsNewUser(browser, "Public Writer", invite);
  member.on("pageerror", (error) => errors.push(error.message));
  if (isMobile) await owner.getByRole("button", { name: "Open navigation" }).click();
  await owner.getByRole("button", { name: "Create channel", exact: true }).click();
  const dialog = owner.getByRole("dialog");
  await dialog.getByLabel("Channel name", { exact: true }).fill("public-workshop");
  await dialog.getByRole("checkbox", { name: "Create a new public text channel", exact: true }).check();
  const publicTitle = `Public Workshop ${testInfo.project.name} ${Date.now()}`;
  await dialog.getByLabel("Public community title", { exact: true }).fill(publicTitle);
  await expect(dialog.getByText(/Existing private history stays private/)).toBeVisible();
  await dialog.getByRole("checkbox", { name: /I understand that this new channel/ }).check();
  await expectNoA11yViolations(owner);
  await dialog.getByRole("button", { name: "Create channel", exact: true }).click();
  await expect(owner.getByRole("heading", { level: 1, name: "public-workshop", exact: true })).toBeVisible();
  if (isMobile) await owner.keyboard.press("Escape");
  const appPath = new URL(owner.url()).pathname;
  const id = appPath.split("/").pop()!;
  await member.goto(appPath);
  await expect(member.getByText(/Public channel: your display name/)).toBeVisible();
  const composer = member.getByRole("textbox", { name: "Message #public-workshop", exact: true });
  await composer.fill("Hello from the explicitly public workshop <script>alert('no')</script>");
  await expect(member.getByRole("button", { name: "Send message", exact: true })).toBeDisabled();
  await member.getByRole("checkbox", { name: "I acknowledge public posting in this channel.", exact: true }).check();
  const posting = member.waitForResponse((response) => response.request().method() === "POST" && new URL(response.url()).pathname === appPath);
  await member.getByRole("button", { name: "Send message", exact: true }).click();
  expect((await posting).status()).toBe(200);
  const posted = member.getByRole("log").getByRole("listitem").filter({ hasText: "Hello from the explicitly public workshop" }).first();
  await expect(posted).toBeVisible();
  await expect(posted).toHaveAttribute("data-message-id", /^[0-9a-f-]{36}$/);
  const messageId = await posted.getAttribute("data-message-id");
  expect(messageId).toMatch(/^[0-9a-f-]{36}$/);
  const row = member.locator(`[data-message-id="${messageId}"]`);
  await row.hover();
  await row.getByRole("button", { name: "Edit message", exact: true }).click();
  await row.getByRole("textbox", { name: "Edit message", exact: true }).fill("Edited public workshop text");
  await expect(row.getByRole("button", { name: "save", exact: true })).toBeDisabled();
  await row.getByRole("checkbox", { name: "I acknowledge publishing this edit.", exact: true }).check();
  await row.getByRole("button", { name: "save", exact: true }).click();
  await expect(row.getByText("Edited public workshop text", { exact: true })).toBeVisible();
  await expectNoA11yViolations(member);
  await member.screenshot({ path: testInfo.outputPath("public-composer.png"), fullPage: true });
  const anon = await newUserPage(browser);
  const requests: string[] = [];
  anon.on("request", (request) => requests.push(new URL(request.url()).pathname));
  anon.on("pageerror", (error) => errors.push(error.message));
  const directory = await anon.goto("/discover");
  expect(directory!.headers()["cache-control"]).toContain("no-store");
  await anon.locator("li").filter({ hasText: publicTitle }).getByRole("link", { name: "#public-workshop", exact: true }).click();
  await expect(anon.getByRole("heading", { level: 1, name: "#public-workshop", exact: true })).toBeVisible();
  await expect(anon.getByText("Public Writer", { exact: true })).toBeVisible();
  await expect(anon.getByText("Edited public workshop text", { exact: true })).toBeVisible();
  await expectNoA11yViolations(anon);
  expect(await anon.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await anon.screenshot({ path: testInfo.outputPath("anonymous-public-channel.png"), fullPage: true });
  expect(requests.some((path) => path.startsWith("/api/") || path.startsWith("/app/"))).toBe(false);
  const html = await (await anon.request.get(`/public/${id}?_rsc=boundary`, { headers: { RSC: "1" } })).text();
  expect(html).not.toContain("PRIVATE WORKSHOP NAME");
  expect(html).not.toContain("authorId");
  expect(html).not.toContain("/api/attachments");
  expect((await anon.request.get(`/public/${privateId}`)).status()).toBe(404);
  const sitemap = await anon.request.get("/sitemap.xml");
  expect(sitemap.headers()["cache-control"]).toContain("no-store");
  expect(await sitemap.text()).toContain(`/public/${id}`);
  await anon.getByRole("link", { name: "Report post", exact: true }).click();
  await expect(anon).toHaveURL(/\/sign-in/);
  const reporter = await newUserPage(browser);
  await signUp(reporter, "Public Reporter");
  await reporter.goto(`/public/${id}`);
  await reporter.getByRole("link", { name: "Report post", exact: true }).click();
  await expect(reporter.getByText(/You do not need to join/)).toBeVisible();
  await reporter.getByLabel("Reason (3–512 characters)", { exact: true }).fill("Review this public message please");
  await reporter.getByRole("button", { name: "Submit report", exact: true }).click();
  await expect(reporter.getByRole("heading", { name: "Report submitted", exact: true })).toBeVisible();
  owner.once("dialog", (dialog) => dialog.accept());
  await owner.getByRole("button", { name: "Unpublish permanently", exact: true }).click();
  await expect(owner.getByText(/Permanently unpublished/)).toBeVisible();
  expect((await anon.request.get(`/public/${id}`)).status()).toBe(404);
  expect((await anon.request.get(`/public/${id}`, { headers: { RSC: "1" } })).status()).toBe(404);
  expect(await (await anon.request.get("/discover")).text()).not.toContain(publicTitle);
  expect(await (await anon.request.get("/sitemap.xml")).text()).not.toContain(`/public/${id}`);
  await anon.goto("/privacy");
  await expect(anon.getByRole("heading", { name: "Public channels", exact: true })).toBeVisible();
  await expect(anon.getByText(/Later profile renames do not change a stored public name/)).toBeVisible();
  await expectNoA11yViolations(anon);
  expect(errors).toEqual([]);
  for (const page of [owner, member, anon, reporter]) await page.context().close();
});
